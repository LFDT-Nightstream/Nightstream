//! Exact optimized NIFS evidence for the fixed F-prime carrier fixture.
//!
//! Owns: the legacy carrier counterexample (`1 x 257` all-zero R1CS),
//! deterministic preprocessing seed 41, canonical fixed-k zero accumulator,
//! one honest zero witness, one witness changed only at the first completed
//! Phi81 carrier coordinate, and a drift-checked Lean data export.
//!
//! Does not own: independent NC semantics, a general Pi_CCS/NIFS refinement,
//! F-prime acceptance, a production relation choice, R1CS lowering, constraint
//! removal, or constraint counts.
//!
//! | Protocol | Phase | Family | Exported evidence |
//! |---|---|---|---|
//! | F-prime / NIFS | fixed carrier | verifier-owned CCS structure | exact rows, columns, arity, degree, public width, and structure digest |
//! | Pi_CCS | fresh witness | completed Phi81 carrier | logical views agree; full views differ only from coordinate 257 onward |
//! | Pi_CCS | initial accumulator | canonical fixed-k zero | exact running-claim count |
//! | Pi_CCS | optimized prove / verify | public API | both exact claims verify under the same fixed structure and transcript schedule |
//! | NIFS | optimized prove / verify | fixed Construction-2 API | exact prover/verifier outcomes for both claims |
//! | F-prime | recursive NIFS.V | repaired physical carrier boundary | exact rejection outcome for a linked 257-wide input with the same bad tail |
//! | implementation refinement | Rust to Lean | artifact drift | exact generated bytes or a review-only `.expected` file |

