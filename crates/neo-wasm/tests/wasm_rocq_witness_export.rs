//! Export a real trace's rows to Rocq, so the refinement theorem's premises can be
//! checked against an actual run (`formal/wasm-rocq/tests/BlockCallWitness.v`).
//! Regenerate with `cargo test -p neo-wasm --release --test wasm_rocq_witness_export -- --ignored`.

use neo_wasm::host_event_bindings::HostEventBindings;
use neo_wasm::witness_builder::build_witness_vector;
use neo_wasm::{collect_wasmtime_steps, traces_from_wasmtime_steps, WasmAuxOpcode, WasmRowKind};
use p3_field::PrimeField64;
use std::fmt::Write;

/// `tests/BlockCalls.v`'s program: a call from inside two blocks.
const BLOCK_CALLS: &str = r#"(module
  (func $readZero (result i32) (local i32) local.get 0)
  (func (export "main") (result i32) (local i32)
    block block call $readZero local.set 0 end end local.get 0))"#;

#[test]
#[ignore = "regenerates a Rocq file"]
fn export_block_call_witness() {
    let wasm = wat::parse_str(BLOCK_CALLS).expect("wat");
    let run = collect_wasmtime_steps(&wasm, &HostEventBindings::default(), "main", &[]).expect("trace");
    let trace = traces_from_wasmtime_steps(&run.steps).expect("normalize");
    // The caller's frame from its local zeroing until just before its final END,
    // which finishes the activation.
    let start = trace
        .iter()
        .position(|row| row.row_kind == WasmRowKind::Aux(WasmAuxOpcode::LocalZero))
        .expect("the caller's local zeroing");
    let end = trace
        .iter()
        .position(|row| row.state_after.activation_finished)
        .expect("the final return");
    let mut out = String::from(
        "(* AUTO-GENERATED by tests/wasm_rocq_witness_export.rs. DO NOT EDIT. *)\n\
         From Stdlib Require Import List ZArith.\nImport ListNotations.\nOpen Scope Z_scope.\n\n\
         (* Each row's witness, column by column, in trace order. *)\n\
         Definition blockCallRows : list (list Z) :=\n  [",
    );
    for (index, row) in trace[start..end].iter().enumerate() {
        assert!(
            row.row_kind.is_program()
                || matches!(
                    row.row_kind,
                    WasmRowKind::Aux(WasmAuxOpcode::LocalZero | WasmAuxOpcode::FrameMove)
                ),
            "row {index} is outside the caller's run: {:?}",
            row.row_kind
        );
        if index > 0 {
            out.push_str(";\n   ");
        }
        // Dense rows: Rocq looks columns up by position, so cost stays linear in the
        // column index instead of in comparisons of unary column numbers.
        let entries = build_witness_vector(row)
            .iter()
            .map(|value| value.as_canonical_u64().to_string())
            .collect::<Vec<_>>()
            .join("; ");
        write!(out, "[{entries}]").unwrap();
    }
    out.push_str("].\n");
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../formal/wasm-rocq/tests/BlockCallTrace.v");
    std::fs::write(&path, out).expect("write");
}
