#!/usr/bin/env python3
"""Write the Rust Poseidon2 constants from params.json.

Run `python3 scripts/poseidon2/emit_rust.py`. It writes
crates/neo-ccs/src/crypto/poseidon2_constants.rs. The neo-ccs test
`poseidon2_params` fails when that file and params.json differ.
"""

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
TARGET = HERE.parents[1] / "crates/neo-ccs/src/crypto/poseidon2_constants.rs"


def row(values, indent):
    return " " * indent + "[" + ", ".join(f"Fq::new({v})" for v in values) + "],\n"


def rows(name, table):
    return f"    {name}: [\n" + "".join(row(r, 8) for r in table) + "    ],\n"


def instance(inst):
    t = inst["t"]
    assert (inst["d"], inst["rf"], inst["rp"]) == (7, 8, 22), "the Rust permutation fixes x^7 and 8 + 22 rounds"
    return (
        f"/// `{inst['label']}`\n"
        f"pub static INSTANCE_{t}: Instance<{t}> = Instance {{\n"
        + rows("initial", inst["external_initial"])
        + rows("terminal", inst["external_terminal"])
        + "    internal:\n" + row(inst["internal"], 8).rstrip(",\n") + ",\n"
        + "    diagonal:\n" + row(inst["internal_diagonal"], 8).rstrip(",\n") + ",\n"
        + "};\n"
    )


def main():
    params = json.loads((HERE / "params.json").read_text())
    text = (
        "// Generated by scripts/poseidon2/emit_rust.py from scripts/poseidon2/params.json. Do not edit.\n\n"
        "use super::poseidon2::Instance;\n"
        "use neo_math::Fq;\n\n"
        + "\n".join(instance(inst) for inst in params["instances"])
    )
    TARGET.write_text(text)
    print(f"wrote {TARGET.relative_to(HERE.parents[1])}")


if __name__ == "__main__":
    main()
