//! Exports the wasm base R1CS relation as Rocq source for `formal/wasm-rocq`.
//!
//! This binary owns the Rust→Rocq code-emission wiring. It does not own the
//! circuit data — that lives in `neo-application`'s tagged R1CS builder and
//! catalog, and in the shared `define_column_region!` macro.
//!
//! Outputs, all in `formal/wasm-rocq/`:
//! - `Columns.v` — the complete base witness column registry and widths.
//! - `FullRelation.v` — every base R1CS row; the compact operation circuit is separate.
//! - `MemoryCatalog.v` — logical memory ports and cross-step continuity links.
//! - `OpcodeCatalog.v` — opcode bytes used by the program ROM.

use neo_application::{ApplicationRelation, ColumnWidth, MemoryKind, MemoryPortActivation, MemoryPortKind};
use neo_math::{balanced::to_balanced_i128, F};
use neo_wasm::ccs::build_wasm_relation;
use neo_wasm::isa::{opcode_code, WasmOpcode};
use neo_wasm::layout::{
    selector_col, COL_CALL_STACK_PUSH_PRESENT, COL_HOST_CALL_ACTIVE, COL_LOCAL_VALUE, COL_ONE, COL_OUTPUT_CAPTURED,
    COL_SP_AFTER, COL_STACK_READS, COL_STACK_READ_ACTIVE, COL_STACK_READ_ADDR_LO, COL_STACK_WRITE0_ACTIVE,
    COL_STACK_WRITE0_ADDR_HI, COL_STACK_WRITE0_ADDR_LO, COL_STACK_WRITE0_HI_ACTIVE, COL_STACK_WRITES,
    NAMED_COLUMN_COUNT,
};
use neo_wasm::relation_layout::build_wasm_relation_layout;
use neo_wasm::tagged_r1cs_builder::WasmConstraintScope;
use neo_wasm::WasmMemoryId;
use std::fs;
use std::path::PathBuf;

fn rocq_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../formal/wasm-rocq")
}

fn emit_rocq_terms(terms: &[(usize, F)]) -> String {
    let entries = terms
        .iter()
        .map(|(column, coefficient)| format!("({column}%nat, {})", to_balanced_i128(*coefficient)))
        .collect::<Vec<_>>();
    format!("[{}]", entries.join("; "))
}

fn rocq_width(width: ColumnWidth) -> String {
    match width {
        ColumnWidth::Boolean => "Boolean".to_string(),
        ColumnWidth::Byte => "Byte".to_string(),
        ColumnWidth::U32 => "U32".to_string(),
        ColumnWidth::Bits(bits) => format!("(Bits {bits}%nat)"),
        ColumnWidth::Field => "Field".to_string(),
    }
}

fn emit_rocq_columns(relation: &ApplicationRelation<WasmConstraintScope>) -> String {
    let mut out = String::from(
        "(* AUTO-GENERATED by export_wasm_rocq. DO NOT EDIT. *)\nFrom Stdlib Require Import List.\nImport ListNotations.\n\nInductive Width := Boolean | Byte | U32 | Bits (n : nat) | Field.\nDefinition Family := (nat * nat * Width)%type.\n\n",
    );
    for family in relation.columns().families() {
        if family.len == 1 {
            out.push_str(&format!("Definition {} : nat := {}%nat.\n", family.name, family.start));
        } else if family.len > 64 {
            out.push_str(&format!(
                "Definition {} : list nat := seq {}%nat {}%nat.\n",
                family.name, family.start, family.len
            ));
        } else {
            let indices = (family.start..family.end())
                .map(|index| format!("{index}%nat"))
                .collect::<Vec<_>>()
                .join("; ");
            out.push_str(&format!("Definition {} : list nat := [{indices}].\n", family.name));
        }
    }
    out.push_str(&format!(
        "\nDefinition namedColumnCount : nat := {NAMED_COLUMN_COUNT}%nat.\nDefinition columnCount : nat := {}%nat.\n\n",
        relation.columns().column_count()
    ));
    out.push_str("Definition families : list Family :=\n  [");
    for (index, family) in relation.columns().families().iter().enumerate() {
        if index > 0 {
            out.push_str(";\n   ");
        }
        out.push_str(&format!(
            "({}%nat, {}%nat, {})",
            family.start,
            family.len,
            rocq_width(family.width)
        ));
    }
    out.push_str("].\n");
    out
}

fn emit_rocq_full_relation(relation: &ApplicationRelation<WasmConstraintScope>) -> String {
    let catalog = relation.r1cs().catalog();
    let mut out = String::from(
        "(* AUTO-GENERATED by export_wasm_rocq. DO NOT EDIT. *)\nFrom Stdlib Require Import List ZArith.\nRequire Import R1CS Columns.\nImport ListNotations.\nOpen Scope Z_scope.\n\n",
    );
    out.push_str(&format!(
        "Definition publicInputCount : nat := {}%nat.\nDefinition oneColumn : nat := {}%nat.\nDefinition rowCount : nat := {}%nat.\n\nDefinition rows : list Row :=\n  [",
        relation.r1cs().public_input_count(),
        relation.r1cs().const_one_column(),
        catalog.len()
    ));
    for (index, tagged) in catalog.rows().iter().enumerate() {
        if index > 0 {
            out.push_str(";\n   ");
        }
        let row = tagged.row();
        out.push_str(&format!(
            "({}, {}, {})",
            emit_rocq_terms(row.a_terms()),
            emit_rocq_terms(row.b_terms()),
            emit_rocq_terms(row.c_terms())
        ));
    }
    out.push_str("].\n\nDefinition satFull (w : Witness) : Prop :=\n  w oneColumn = 1 /\\ satAll w rows.\n\n");
    for (label, opcode, name) in [
        ("i32.add relation", WasmOpcode::I32Add, "addRowIndex"),
        ("i32.sub relation", WasmOpcode::I32Sub, "subRowIndex"),
    ] {
        let rows: Vec<_> = catalog
            .rows()
            .iter()
            .enumerate()
            .filter(|(_, row)| row.tag().label() == label)
            .collect();
        let [(index, row)] = rows.as_slice() else {
            panic!("expected exactly one tagged {label} row");
        };
        assert!(matches!(row.tag().owner(), WasmConstraintScope::Opcode(owner) if *owner == opcode));
        out.push_str(&format!("Definition {name} : nat := {index}%nat.\n"));
    }
    for (opcode, name) in [
        (WasmOpcode::LocalGet, "localGetCopyRowIndex"),
        (WasmOpcode::LocalSet, "localSetCopyRowIndex"),
    ] {
        let selector = selector_col(opcode).unwrap();
        let mut matches = catalog.rows().iter().enumerate().filter(|(_, tagged)| {
            let row = tagged.row();
            tagged.tag().label() == "locals value constraints"
                && row
                    .a_terms()
                    .first()
                    .is_some_and(|(col, _)| *col == selector)
                && row
                    .b_terms()
                    .first()
                    .is_some_and(|(col, _)| *col == COL_LOCAL_VALUE)
        });
        let (index, _) = matches
            .next()
            .unwrap_or_else(|| panic!("missing row for {name}"));
        assert!(matches.next().is_none(), "ambiguous row for {name}");
        out.push_str(&format!("Definition {name} : nat := {index}%nat.\n"));
    }
    emit_stack_proof_indices(relation, &mut out);
    out
}

// Select a tagged row by the first column of one factor, never by its position.
// Rocq still checks the actual row shape before using the index in a proof.
#[derive(Clone, Copy)]
enum Factor {
    A,
    B,
    C,
}

fn emit_stack_proof_indices(relation: &ApplicationRelation<WasmConstraintScope>, out: &mut String) {
    use Factor::{A, B, C};
    let catalog = relation.r1cs().catalog();
    let column = |name| {
        relation
            .columns()
            .families()
            .iter()
            .find(|family| family.name == name)
            .unwrap_or_else(|| panic!("missing column family {name}"))
            .start
    };
    for (name, label, factor, column) in [
        (
            "outputCaptureSupportRow",
            "memory activation support",
            A,
            COL_OUTPUT_CAPTURED,
        ),
        (
            "hostCallSupportRow",
            "memory activation support",
            A,
            COL_HOST_CALL_ACTIVE,
        ),
        (
            "hostCallParamsRow",
            "host-event gather binding",
            C,
            column("GHC_PARAMS"),
        ),
        (
            "gatherMemoryKindRow",
            "host-event gather binding",
            C,
            column("GMEM_LOCAL"),
        ),
        ("gatherHighLimbRow", "host-event gather binding", C, column("GK2_HI")),
        (
            "localIndexGateRow",
            "program immediate gates",
            A,
            column("COL_PROGRAM_LOCAL_INDEX_ACTIVE"),
        ),
        (
            "localWriteGateIndex",
            "locals write gate",
            A,
            column("COL_LOCAL_WRITE_ENABLED"),
        ),
        (
            "guestEntryFlagRow",
            "guest call flag",
            C,
            column("COL_GUEST_ENTRY_ACTIVE"),
        ),
        ("localsBasePreservedRow", "locals fbp transition", A, COL_ONE),
        (
            "stackRead1SupportRow",
            "memory activation support",
            A,
            COL_STACK_READ_ACTIVE[1],
        ),
        (
            "nullaryWriteAddressRow",
            "stack write0 addr = sp_before",
            B,
            COL_STACK_WRITE0_ADDR_LO,
        ),
        (
            "unaryReadAddressRow",
            "stack read0 addr = sp_before - 1",
            B,
            COL_STACK_READ_ADDR_LO[0],
        ),
        ("stackReadsArityRow", "fixed stack arity", B, COL_STACK_READS),
        ("stackWritesArityRow", "fixed stack arity", B, COL_STACK_WRITES),
        ("stackReadsActiveRow", "unlabeled", A, COL_STACK_READ_ACTIVE[0]),
        ("stackWritesActiveRow", "unlabeled", A, COL_STACK_WRITE0_ACTIVE),
        (
            "stackRead2SupportRow",
            "memory activation support",
            A,
            COL_STACK_READ_ACTIVE[2],
        ),
        (
            "stackWriteHighActiveRow",
            "host-event gather binding",
            A,
            COL_STACK_WRITE0_HI_ACTIVE,
        ),
        ("callStackPushRow", "guest call flag", C, COL_CALL_STACK_PUSH_PRESENT),
        ("callStackPopSupportRow", "return pc restoration", B, COL_ONE),
        (
            "binaryRead0AddressRow",
            "stack read0 addr = sp_before - 2",
            B,
            COL_STACK_READ_ADDR_LO[0],
        ),
        (
            "binaryRead1AddressRow",
            "stack read1 addr = sp_before - 1",
            B,
            COL_STACK_READ_ADDR_LO[1],
        ),
        (
            "binaryWriteAddressRow",
            "stack write0 addr = sp_before - 2",
            B,
            COL_STACK_WRITE0_ADDR_LO,
        ),
        (
            "stackWriteHighAddressRow",
            "stack high limb addresses",
            A,
            COL_STACK_WRITE0_ADDR_HI,
        ),
        ("stackPointerBalanceRow", "unlabeled", A, COL_SP_AFTER),
        ("stackFrameBasePreservedRow", "stack frame base transition", A, COL_ONE),
        ("gmemLocalBooleanRow", "GMEM_LOCAL", A, column("GMEM_LOCAL")),
        ("gmemOutputBooleanRow", "GMEM_OUTPUT", A, column("GMEM_OUTPUT")),
        ("gmemByteBooleanRow", "GMEM_BYTE", A, column("GMEM_BYTE")),
        ("gmemHalfBooleanRow", "GMEM_HALF", A, column("GMEM_HALF")),
        (
            "stackRead0BooleanRow",
            "COL_STACK_READ_ACTIVE",
            A,
            COL_STACK_READ_ACTIVE[0],
        ),
        (
            "stackRead1BooleanRow",
            "COL_STACK_READ_ACTIVE",
            A,
            COL_STACK_READ_ACTIVE[1],
        ),
    ] {
        let mut matches = catalog.rows().iter().enumerate().filter(|(_, tagged)| {
            let row = tagged.row();
            let terms = match factor {
                A => row.a_terms(),
                B => row.b_terms(),
                C => row.c_terms(),
            };
            tagged.tag().label() == label && terms.first().is_some_and(|(first, _)| *first == column)
        });
        let (index, _) = matches
            .next()
            .unwrap_or_else(|| panic!("missing row for {name}: {label}"));
        assert!(matches.next().is_none(), "ambiguous row for {name}: {label}");
        out.push_str(&format!("Definition {name} : nat := {index}%nat.\n"));
    }
}

fn emit_rocq_memory_catalog() -> String {
    let layout = build_wasm_relation_layout();
    let memories = layout.auxiliary.memory.entries();
    let mut out = String::from(
        "(* AUTO-GENERATED by export_wasm_rocq. DO NOT EDIT. *)\nFrom Stdlib Require Import List.\nRequire Import MemoryTrace.\nImport ListNotations.\n\nDefinition memories : list MemorySpec :=\n  [",
    );
    for (memory_index, memory) in memories.iter().enumerate() {
        if memory_index > 0 {
            out.push_str(";\n   ");
        }
        let kind = match memory.kind {
            MemoryKind::Ram => "Ram",
            MemoryKind::Rom => "Rom",
        };
        out.push_str(&format!(
            "(* {} *) mkMemory {memory_index}%nat {kind} [",
            memory.id.name()
        ));
        for (port_index, port) in memory.ports.iter().enumerate() {
            if port_index > 0 {
                out.push_str("; ");
            }
            let address = port
                .address_columns
                .iter()
                .map(|column| format!("{column}%nat"))
                .collect::<Vec<_>>()
                .join("; ");
            let kind = match port.kind {
                MemoryPortKind::Read => "Read".to_string(),
                MemoryPortKind::Write { value_before_column } => match value_before_column {
                    Some(column) => format!("(Write (Some {column}%nat))"),
                    None => "(Write None)".to_string(),
                },
            };
            let activation = match port.activation {
                MemoryPortActivation::Always => "Always".to_string(),
                MemoryPortActivation::When(column) => format!("(When {column}%nat)"),
                MemoryPortActivation::Unless(column) => format!("(Unless {column}%nat)"),
            };
            out.push_str(&format!(
                "mkPort [{address}] {}%nat {kind} {activation}",
                port.value_column
            ));
        }
        out.push(']');
    }
    out.push_str("].\n\n");
    for (id, name) in [
        (WasmMemoryId::Stack, "stackId"),
        (WasmMemoryId::CallStackReturnPc, "callStackReturnPcId"),
        (WasmMemoryId::CallStackCallerFbp, "callStackCallerFbpId"),
        (WasmMemoryId::CallStackCallerSpBase, "callStackCallerSpBaseId"),
        (WasmMemoryId::FunctionLocalCount, "functionLocalCountId"),
        (WasmMemoryId::FunctionCallMetadata, "functionCallMetadataId"),
        (WasmMemoryId::PcFunctionRef, "pcFunctionRefId"),
        (WasmMemoryId::CallTarget, "callTargetId"),
        (WasmMemoryId::FunctionEntry, "functionEntryId"),
        (WasmMemoryId::ProgramOpcode, "programOpcodeId"),
        (WasmMemoryId::ProgramLocalIndex, "programLocalIndexId"),
        (WasmMemoryId::PcEdgeKind, "pcEdgeKindId"),
        (WasmMemoryId::PcRom, "pcRomId"),
    ] {
        let index = memories
            .iter()
            .position(|memory| memory.id == id)
            .expect("exported memory exists");
        out.push_str(&format!("Definition {name} : nat := {index}%nat.\n"));
    }
    out.push('\n');
    out.push_str("Definition continuityLinks : list ContinuityLink :=\n  [");
    for (index, link) in layout.auxiliary.continuity.links().enumerate() {
        if index > 0 {
            out.push_str(";\n   ");
        }
        out.push_str(&format!(
            "({}%nat, {}%nat)",
            link.previous_step_column, link.next_step_column
        ));
    }
    out.push_str("].\n");
    out
}

fn emit_rocq_opcodes() -> String {
    let mut out =
        String::from("(* AUTO-GENERATED by export_wasm_rocq. DO NOT EDIT. *)\nFrom Stdlib Require Import List ZArith.\nRequire Import R1CS Columns.\nImport ListNotations.\n\n");
    for opcode in WasmOpcode::supported() {
        out.push_str(&format!(
            "Definition CODE_{} : Z := {}%Z.\n",
            opcode.name().to_ascii_uppercase(),
            opcode_code(opcode)
        ));
    }
    out.push_str("\nDefinition selectorCodes : SparseRow :=\n  [");
    for (index, opcode) in WasmOpcode::supported().into_iter().enumerate() {
        if index > 0 {
            out.push_str(";\n   ");
        }
        out.push_str(&format!(
            "({}%nat, CODE_{})",
            selector_col(opcode).expect("supported opcode selector"),
            opcode.name().to_ascii_uppercase()
        ));
    }
    out.push_str("].\n");
    out
}

fn main() -> std::io::Result<()> {
    let dir = rocq_dir();
    fs::create_dir_all(&dir)?;
    let relation = build_wasm_relation().expect("build wasm relation");
    for (name, source) in [
        ("Columns.v", emit_rocq_columns(&relation)),
        ("FullRelation.v", emit_rocq_full_relation(&relation)),
        ("MemoryCatalog.v", emit_rocq_memory_catalog()),
        ("OpcodeCatalog.v", emit_rocq_opcodes()),
    ] {
        let path = dir.join(name);
        fs::write(&path, source)?;
        println!("wrote {}", path.display());
    }
    Ok(())
}
