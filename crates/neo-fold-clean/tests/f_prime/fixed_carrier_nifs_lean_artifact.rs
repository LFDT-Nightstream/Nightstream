#[test]
fn fixed_carrier_nifs_lean_artifact_matches_runtime() {
    assert_eq!(D, 54, "the artifact is specialized to Phi81");
    assert_eq!(F_PRIME_PUBLIC_INPUT_LEN, 257);
    assert_eq!(FIRST_COMPLETED_TAIL, 257);
    assert_eq!(FIRST_TAIL_BLOCK, 4);
    assert_eq!(FIRST_TAIL_LANE, 41);

    let snapshot = capture();
    assert_eq!(snapshot.relation_rows, 1);
    assert_eq!(snapshot.relation_columns, 257);
    assert_eq!(snapshot.relation_arity, 3);
    assert_eq!(snapshot.relation_degree, 2);
    assert_eq!(snapshot.public_input_len, 257);
    assert_eq!(snapshot.nc_bound, 2);
    assert_eq!(snapshot.packed_rows, 54);
    assert_eq!(snapshot.packed_columns, 5);
    assert!(snapshot.fresh_public_inputs_equal);
    assert!(snapshot.commitments_differ);
    assert_eq!(snapshot.zero_logical_decode, snapshot.tail_logical_decode);
    assert_ne!(snapshot.zero_full_decode, snapshot.tail_full_decode);
    assert_eq!(snapshot.tail_full_decode[FIRST_COMPLETED_TAIL], (TAIL_VALUE, 0));
    assert!(snapshot.zero_pi_ccs_accepted);
    assert!(snapshot.tail_pi_ccs_accepted);
    assert!(snapshot.zero_nifs_proved);
    assert!(snapshot.zero_nifs_verified);
    assert!(snapshot.tail_nifs_proved);
    assert!(snapshot.tail_nifs_verified);
    assert_eq!(snapshot.linked_public_input.len(), F_PRIME_PUBLIC_INPUT_LEN);
    assert_eq!(snapshot.linked_public_input[0], 1);
    assert_eq!(snapshot.linked_tail_full_decode.len(), D * 5);
    assert_eq!(snapshot.linked_tail_full_decode[FIRST_COMPLETED_TAIL], (TAIL_VALUE, 0));
    assert!(snapshot.linked_tail_nifs_proved);
    assert!(snapshot.linked_tail_nifs_verified);
    assert!(!snapshot.linked_recursive_f_prime_built);
    assert!(!snapshot.linked_recursive_f_prime_satisfied);

    let emitted = emit_lean(&snapshot);
    let path = format!("{}{}", env!("CARGO_MANIFEST_DIR"), ARTIFACT_REL_PATH);
    let committed = std::fs::read_to_string(&path).unwrap_or_default();
    if committed != emitted {
        let expected_path = format!("{path}.expected");
        let parent = std::path::Path::new(&expected_path)
            .parent()
            .expect("artifact path has a parent");
        std::fs::create_dir_all(parent).expect("create generated artifact directory");
        std::fs::write(&expected_path, &emitted).expect("write .expected artifact");
        panic!(
            "fixed-carrier NIFS Lean artifact drifted. Wrote {expected_path}; inspect it and promote it deliberately."
        );
    }
}
