//! Exports the wasm zkVM's R1CS arithmetization as zkLean-compatible Lean
//! source files.
//!
//! This binary owns the Rust→Lean code-emission wiring. It does not own the
//! circuit data — that lives in `WasmTaggedR1csBuilder` / `WasmConstraintCatalog`
//! (see `crates/neo-wasm/src/`) and in the `define_column_region!` macro
//! in `wasm/layout.rs`.
//!
//! Outputs:
//! - `formal/wasm-zklean/WasmCircuit/Columns.lean` — column index definitions
//!   derived from `COLUMN_SPECS` (single source of truth: the macro).
//! - `formal/wasm-zklean/WasmCircuit/Generated.lean` — a tiny demo circuit
//!   built by mirroring `push_zero_test_gadget` (see
//!   `crates/neo-wasm/src/gadgets.rs`). Emits the flat R1CS rows
//!   the Rust builder produced, the matching `Instr` trace, and a
//!   `native_decide`-checked cross-check theorem.

use neo_math::F;
use neo_wasm::layout::{COLUMN_SPECS, COL_ONE, NAMED_COLUMN_COUNT};
use neo_wasm::push_zero_test_gadget;
use neo_wasm::tagged_r1cs_builder::WasmTaggedR1csBuilder;
use p3_field::PrimeField64;
use std::fs;
use std::path::PathBuf;

const GOLDILOCKS_P: i128 = (1i128 << 64) - (1i128 << 32) + 1;

fn formal_dir() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../formal/wasm-zklean/WasmCircuit")
}

fn strip_col_prefix_lower(name: &str) -> String {
    name.strip_prefix("COL_")
        .unwrap_or(name)
        .to_ascii_lowercase()
}

fn snake_to_camel(snake: &str) -> String {
    let mut out = String::new();
    let mut next_upper = false;
    for c in snake.chars() {
        if c == '_' {
            next_upper = true;
        } else if next_upper {
            out.push(c.to_ascii_uppercase());
            next_upper = false;
        } else {
            out.push(c);
        }
    }
    out
}

/// Balanced-residue conversion: maps Goldilocks field elements to their
/// signed-integer representation in [-p/2, p/2]. Lets us emit `-1` instead of
/// `18446744069414584320` in the Lean output.
fn f_to_int(x: F) -> i128 {
    let u = x.as_canonical_u64() as i128;
    if u > GOLDILOCKS_P / 2 {
        u - GOLDILOCKS_P
    } else {
        u
    }
}

fn emit_columns() -> String {
    let mut out = String::new();
    out.push_str("-- AUTO-GENERATED by `cargo run --bin export_wasm_zklean`.\n");
    out.push_str("-- DO NOT EDIT BY HAND.\n");
    out.push_str("--\n");
    out.push_str("-- Column index definitions for the wasm zkVM constraint system. The single\n");
    out.push_str("-- source of truth is `crates/neo-wasm/src/layout.rs::COLUMN_SPECS`,\n");
    out.push_str("-- itself derived from the `define_column_region!` macro — Lean names here are in\n");
    out.push_str("-- lockstep with the Rust `COL_*` constants by construction.\n");
    out.push('\n');
    out.push_str("namespace WasmCircuit.Columns\n");
    out.push('\n');
    for spec in COLUMN_SPECS {
        let snake = strip_col_prefix_lower(spec.name);
        let camel = snake_to_camel(&snake);
        if !spec.role.is_empty() {
            out.push_str(&format!("/-- {} -/\n", spec.role));
        }
        if spec.len == 1 {
            out.push_str(&format!("def {camel} : Nat := {}\n", spec.start));
        } else {
            let indices = (spec.start..spec.end())
                .map(|column| column.to_string())
                .collect::<Vec<_>>()
                .join(", ");
            out.push_str(&format!("def {camel} : Array Nat := #[{indices}]\n"));
        }
    }
    out.push('\n');
    out.push_str(&format!("def namedColumnCount : Nat := {NAMED_COLUMN_COUNT}\n"));
    out.push('\n');
    out.push_str("end WasmCircuit.Columns\n");
    out
}

/// Demo circuit: a single real `push_zero_test_gadget` invocation on
/// synthetic column indices. The cross-check in `Generated.lean` validates
/// that the rows the real gadget produces equal what `instrToRows` lowers
/// `Instr.ZeroTest` to.
struct DemoCircuit {
    rows: Vec<(Vec<(usize, F)>, Vec<(usize, F)>, Vec<(usize, F)>)>,
    /// Column indices used by the gadget, in `Instr.ZeroTest` order.
    value: usize,
    inv_witness: usize,
    is_zero: usize,
}

fn build_demo_zero_test_circuit() -> DemoCircuit {
    let value = 1usize;
    let inv_witness = 2usize;
    let is_zero = 3usize;
    let width = 8;
    let mut builder = WasmTaggedR1csBuilder::new(width, COL_ONE).expect("builder construction");

    push_zero_test_gadget(&mut builder, value, inv_witness, is_zero);

    let (_structure, catalog) = builder.build().expect("build");
    let rows = catalog
        .rows
        .into_iter()
        .map(|r| (r.a_terms, r.b_terms, r.c_terms))
        .collect();
    DemoCircuit {
        rows,
        value,
        inv_witness,
        is_zero,
    }
}

fn emit_terms(terms: &[(usize, F)]) -> String {
    if terms.is_empty() {
        return "[]".to_string();
    }
    let parts: Vec<String> = terms
        .iter()
        .map(|(idx, coeff)| {
            let c = f_to_int(*coeff);
            if c < 0 {
                format!("({idx}, ({c}))")
            } else {
                format!("({idx}, {c})")
            }
        })
        .collect();
    format!("[{}]", parts.join(", "))
}

fn emit_rows(rows: &[(Vec<(usize, F)>, Vec<(usize, F)>, Vec<(usize, F)>)]) -> String {
    let parts: Vec<String> = rows
        .iter()
        .map(|(a, b, c)| format!("({}, {}, {})", emit_terms(a), emit_terms(b), emit_terms(c)))
        .collect();
    format!("[ {} ]", parts.join(",\n    "))
}

fn emit_generated() -> String {
    let demo = build_demo_zero_test_circuit();
    let DemoCircuit {
        rows,
        value,
        inv_witness,
        is_zero,
    } = &demo;

    let mut out = String::new();
    out.push_str("-- AUTO-GENERATED by `cargo run --bin export_wasm_zklean`.\n");
    out.push_str("-- DO NOT EDIT BY HAND. Regenerate from the wasm zkVM constraint catalog.\n");
    out.push_str("--\n");
    out.push_str("-- Demo circuit: one `push_zero_test_gadget` invocation. The `instructions`\n");
    out.push_str("-- value is the structured gadget trace; `actualRows` are the flat R1CS\n");
    out.push_str("-- rows the Rust matrix builder produced. The cross-check theorem fails at\n");
    out.push_str("-- `lake build` time if the Lean `instrToRows` definition drifts from the\n");
    out.push_str("-- Rust gadget. See ../README.md.\n");
    out.push('\n');
    out.push_str("import WasmCircuit.Columns\n");
    out.push_str("import WasmCircuit.Gadgets\n");
    out.push('\n');
    out.push_str("namespace WasmCircuit.Generated\n");
    out.push('\n');
    out.push_str("open WasmCircuit.Gadgets\n");
    out.push('\n');
    out.push_str("/-- Pins the hardcoded `Gadgets.constOneCol` to the macro-driven\n");
    out.push_str("    `Columns.one`. Fails by reflection if the Rust `COL_ONE` ever\n");
    out.push_str("    leaves index 0. -/\n");
    out.push_str("theorem constOneCol_pinned : constOneCol = WasmCircuit.Columns.one := by\n");
    out.push_str("  native_decide\n");
    out.push('\n');
    out.push_str(&format!(
        "def instructions : List Instr :=\n  [ .ZeroTest {value} {inv_witness} {is_zero} ]\n"
    ));
    out.push('\n');
    out.push_str("def actualRows : List Row :=\n  ");
    out.push_str(&emit_rows(rows));
    out.push('\n');
    out.push('\n');
    out.push_str("/-- The structured gadget trace lowers to exactly the rows the Rust matrix\n");
    out.push_str("    builder produced. Decided by reflection: any drift between the Rust\n");
    out.push_str("    gadget and the Lean `instrToRows` definition fails this check. -/\n");
    out.push_str("theorem trace_matches_actual :\n");
    out.push_str("    instructions.flatMap instrToRows = actualRows := by\n");
    out.push_str("  native_decide\n");
    out.push('\n');
    out.push_str("end WasmCircuit.Generated\n");
    out
}

fn write_file(name: &str, contents: &str) -> std::io::Result<()> {
    let dir = formal_dir();
    fs::create_dir_all(&dir)?;
    let path = dir.join(name);
    fs::write(&path, contents)?;
    println!("wrote {}", path.display());
    Ok(())
}

fn main() -> std::io::Result<()> {
    write_file("Columns.lean", &emit_columns())?;
    write_file("Generated.lean", &emit_generated())?;
    Ok(())
}
