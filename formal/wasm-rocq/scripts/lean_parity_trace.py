#!/usr/bin/env python3
"""Write `tests/LeanParityTrace.v` from the Lean parity file of the memory-event copy
(`formal/nightstream-fprime/artifacts/nightstream-fprime-memory-trace-parity-v1.json`). Each
case is its input (catalog, rows, initial cells, queries) and the verdicts that Lean computed.
`tests/LeanParity.v` checks the verdicts with the Rocq definitions. The output is rewritten only
when it changes.

  python3 scripts/lean_parity_trace.py <parity.json> <out.v>"""

import json
from pathlib import Path
import sys


def nats(values):
    return '[' + '; '.join(f'{v}%nat' for v in values) + ']'


def zs(values):
    return '[' + '; '.join(f'{v}' for v in values) + ']'


def port(value):
    address, column, kind, activation = value
    kind = ['Read', '(Write None)', f'(Write (Some {kind[-1]}%nat))'][kind[0]]
    activation = ['Always', f'(When {activation[-1]}%nat)', f'(Unless {activation[-1]}%nat)'][activation[0]]
    return f'mkPort {nats(address)} {column}%nat {kind} {activation}'


def memory(value):
    memory_id, kind, ports = value
    return f'mkMemory {memory_id}%nat {["Rom", "Ram"][kind]} [' + '; '.join(map(port, ports)) + ']'


def option(value):
    return 'None' if value == [0] else f'(Some {value[1]})'


def event(value):
    if value[0] == 0:
        return f'ReadEvent {value[1]}%nat {zs(value[2])} {value[3]}'
    return f'WriteEvent {value[1]}%nat {zs(value[2])} {value[3]} {option(value[4])}'


def case(value):
    (catalog, rows, initial, queries), (events, replays, finals, bounded) = value
    return ('(' + '[' + '; '.join(map(memory, catalog)) + '], '
            + '[' + '; '.join(zs(r) for r in rows) + '], '
            + '[' + '; '.join(f'({m}%nat, {zs(a)}, {v})' for m, a, v in initial) + '], '
            + '[' + '; '.join(f'({m}%nat, {zs(a)})' for m, a in queries) + '], '
            + '([' + '; '.join(map(event, events)) + '], '
            + ['false', 'true'][replays] + ', '
            + '[' + '; '.join(map(option, finals)) + '], '
            + '[' + '; '.join(['false', 'true'][b] for b in bounded) + ']))')


def main():
    source, target = map(Path, sys.argv[1:])
    schema, cases = json.loads(source.read_text())
    if schema != 1:
        raise SystemExit(f'{source}: schema {schema}, expected 1')
    text = ('(* AUTO-GENERATED by scripts/lean_parity_trace.py from the Lean parity file. DO NOT EDIT. *)\n'
            'From Stdlib Require Import List ZArith.\nRequire Import MemoryTrace.\n'
            'Import ListNotations.\nOpen Scope Z_scope.\n\n'
            'Definition cases : list (list MemorySpec * list (list Z) * list (nat * list Z * Z) *\n'
            '    list (nat * list Z) * (list Event * bool * list (option Z) * list bool)) :=\n  [')
    text += ';\n   '.join(map(case, cases)) + '].\n'
    if not target.exists() or target.read_text() != text:
        target.write_text(text)


if __name__ == '__main__':
    main()
