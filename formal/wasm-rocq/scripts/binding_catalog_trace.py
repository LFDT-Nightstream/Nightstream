#!/usr/bin/env python3
"""Write `tests/BindingCatalogTrace.v`: the logical catalog of each binding export of
`export_wasm_rocq --binding`, for `tests/BindingCatalog.v`."""

import json
from pathlib import Path
import sys

from lean_parity_trace import port

SIZES = ['micro', 'small', 'medium', 'large']


def main():
    source, target = map(Path, sys.argv[1:])
    text = ('(* AUTO-GENERATED by scripts/binding_catalog_trace.py from the binding exports. DO NOT EDIT. *)\n'
            'From Stdlib Require Import List.\nRequire Import MemoryTrace.\nImport ListNotations.\n\n')
    for size in SIZES:
        schema, _, _, _, logical = json.loads((source / f'wasm-binding-{size}-v1.json').read_text())[:5]
        if schema != 1:
            raise SystemExit(f'{source}: schema {schema}, expected 1')
        memories = [f'mkMemory {i}%nat {["Rom", "Ram"][kind]} [' + '; '.join(map(port, ports)) + ']'
                    for i, (kind, ports) in enumerate(logical)]
        text += f'Definition {size}Logical : list MemorySpec :=\n  [' + ';\n   '.join(memories) + '].\n\n'
    if not target.exists() or target.read_text() != text:
        target.write_text(text)


if __name__ == '__main__':
    main()
