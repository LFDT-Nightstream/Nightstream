fn fixed_carrier_r1cs() -> R1cs {
    R1cs {
        a: Mat::zero(1, F_PRIME_PUBLIC_INPUT_LEN, F::ZERO),
        b: Mat::zero(1, F_PRIME_PUBLIC_INPUT_LEN, F::ZERO),
        c: Mat::zero(1, F_PRIME_PUBLIC_INPUT_LEN, F::ZERO),
        m_in: F_PRIME_PUBLIC_INPUT_LEN,
    }
}

fn fibonacci_step_r1cs() -> R1csShape {
    // z = [1, a, b, next_a, next_b]
    // b * 1 = next_a
    // (a + b) * 1 = next_b
    let mut a = Mat::zero(2, 5, F::ZERO);
    let mut b = Mat::zero(2, 5, F::ZERO);
    let mut c = Mat::zero(2, 5, F::ZERO);
    a[(0, 2)] = F::ONE;
    b[(0, 0)] = F::ONE;
    c[(0, 3)] = F::ONE;
    a[(1, 1)] = F::ONE;
    a[(1, 2)] = F::ONE;
    b[(1, 0)] = F::ONE;
    c[(1, 4)] = F::ONE;
    R1cs { a, b, c, m_in: 1 }.into()
}

fn f_prime_step_config(prep: &neo_fold_clean::Preprocessing) -> FPrimeStepConfig<'_> {
    FPrimeStepConfig {
        nifs: prep
            .nifs_v_circuit_config()
            .expect("fixed NIFS.V circuit config"),
        b: prep.params.b(),
        transcript_label: F_PRIME_TRANSCRIPT_LABEL,
        public_input_layout: FPrimePublicInputLayout::plain(),
        nebula: None,
        state_x_out_digest_mode: StateXOutDigestMode::Stateful,
    }
}

fn canonical_accumulator_digest(prep: &neo_fold_clean::Preprocessing) -> [F; 4] {
    let zero = RunningInstance::canonical_zero(&prep.params, prep.structure(), F_PRIME_PUBLIC_INPUT_LEN)
        .expect("canonical fixed-k accumulator");
    AccumulatorHandle::from_running_parts(&zero.claims, zero.parent_authority.as_ref()).digest_fields()
}

fn uniform_chunk_digest(prep: &neo_fold_clean::Preprocessing, start_index: u64) -> [F; 4] {
    f_prime_chunk_public_digest_for_uniform_shape(
        start_index,
        1,
        D,
        prep.params.kappa() as usize,
        F_PRIME_PUBLIC_INPUT_LEN,
    )
}

fn native_x_out(
    state: &FPrimeStateIn,
    chunk_digest: [F; 4],
    semantic_state: [F; 4],
    construction2_acc: [F; 4],
    chunk_count: u64,
    step_count: u64,
) -> [F; 4] {
    digest32_as_fields(state_x_out_digest_with_mode(
        StateXOutDigestMode::Stateful,
        digest_fields_as_digest32(state.vk_fs_digest),
        state.pi_ccs_header_bundle,
        &state.pi_ccs_header_bundle,
        chunk_count,
        step_count,
        digest_fields_as_digest32(state.z_0),
        digest_fields_as_digest32(chunk_digest),
        state.pc,
        digest_fields_as_digest32(semantic_state),
        digest_fields_as_digest32(construction2_acc),
        digest_fields_as_digest32(chunk_digest),
        None,
    ))
}

fn append_f_prime_context(tr: &mut Transcript, state: &FPrimeStateIn, chunk_digest: [F; 4]) {
    tr.append_fields(b"f_prime/vk_fs", &state.vk_fs_digest);
    tr.append_fields(b"f_prime/pi_ccs_header", &state.pi_ccs_header_bundle);
    tr.append_fields(b"f_prime/chunk_count_in", &[F::from_u64(state.chunk_count_in)]);
    tr.append_fields(b"f_prime/step_count_in", &[F::from_u64(state.step_count_in)]);
    tr.append_fields(b"f_prime/z_0", &state.z_0);
    tr.append_fields(b"f_prime/z_i_in", &state.z_i_in);
    tr.append_fields(b"f_prime/pc", &[F::from_u64(state.pc)]);
    tr.append_fields(b"f_prime/semantic_state_in", &state.semantic_state_digest_in);
    tr.append_fields(b"f_prime/acc_digest_in", &state.acc_digest_in);
    tr.append_fields(b"f_prime/public_trace_in", &state.public_trace_in);
    tr.append_fields(b"f_prime/chunk_digest", &chunk_digest);
}

fn recursive_source(state: &FPrimeStateIn, prior_x_out: [F; 4], x_out: [F; 4]) -> RecursiveSource {
    let mut image = FPrimeSourceImage::new();
    let chunk_count = image.push_u64_le(state.chunk_count_in);
    let step_count = image.push_u64_le(state.step_count_in);
    let pc = image.push_u64_le(state.pc);
    let prior_public = image.push_f_prime_public_input(prior_x_out);
    let prior_x_out = BitRange::new(prior_public.start() + 1, F_PRIME_ENC_INST_BITS);
    let x_out = image.push_enc_inst(x_out);
    RecursiveSource {
        image,
        chunk_count,
        step_count,
        pc,
        prior_x_out,
        x_out,
    }
}

fn extension_pairs(values: &[K]) -> Vec<(u64, u64)> {
    values.iter().map(KExtensions::to_limbs_u64).collect()
}

fn optimized_pi_ccs_accepts(
    prep: &neo_fold_clean::Preprocessing,
    running: &RunningInstance,
    fresh: CcsInstance,
) -> bool {
    let fresh_claim = fresh.claim.clone();
    let mut prover_transcript = Transcript::session();
    let proof = match pi_ccs::prove(
        &mut prover_transcript,
        &prep.params,
        prep.structure(),
        prep.optimized_cache(),
        &prep.log,
        vec![fresh],
        running,
    ) {
        Ok(proof) => proof,
        Err(_) => return false,
    };

    let verifier_running = running.claims_only();
    let mut verifier_transcript = Transcript::session();
    pi_ccs::verify(
        &mut verifier_transcript,
        &prep.params,
        prep.structure(),
        prep.optimized_cache(),
        core::slice::from_ref(&fresh_claim),
        &verifier_running,
        &proof,
    )
    .is_ok()
}

fn optimized_nifs_outcome(
    prep: &neo_fold_clean::Preprocessing,
    running: &FixedNifsAccumulator,
    fresh: CcsInstance,
) -> (bool, bool) {
    let fresh_claim = fresh.claim.clone();
    let mut prover_transcript = Transcript::session();
    let (_next, proof) = match prove_fixed(
        &mut prover_transcript,
        &prep.params,
        prep.structure(),
        prep.optimized_cache(),
        &prep.log,
        prep.mix_rhos_commits(),
        prep.combine_b_pows(),
        fresh,
        running,
    ) {
        Ok(output) => output,
        Err(_) => return (false, false),
    };

    let verifier_running = match FixedNifsAccumulator::from_verifier_running(
        &prep.params,
        prep.structure(),
        prep.combine_b_pows(),
        running.running().claims_only(),
    ) {
        Ok(running) => running,
        Err(_) => return (true, false),
    };
    let mut verifier_transcript = Transcript::session();
    let verified = verify_fixed(
        &mut verifier_transcript,
        &prep.params,
        prep.structure(),
        prep.optimized_cache(),
        prep.mix_rhos_commits(),
        prep.combine_b_pows(),
        &fresh_claim,
        &verifier_running,
        &proof,
    )
    .is_ok();
    (true, verified)
}

fn linked_recursive_f_prime_outcome(prep: &neo_fold_clean::Preprocessing, carrier: &R1cs) -> LinkedFPrimeOutcome {
    let application = fibonacci_step_r1cs();
    let application_assignment = [F::ONE, F::from_u64(5), F::from_u64(8), F::from_u64(8), F::from_u64(13)];
    let semantic_in = semantic_state_digest_fields(&application_assignment[1..3]);
    let semantic_out = semantic_state_digest_fields(&application_assignment[3..5]);
    let context = FullFPrimeContext::derive(&prep.params, prep.structure(), &prep.log, semantic_in)
        .expect("fixed F-prime verifier context");
    let relation = FullFPrimeRelation::new(context, f_prime_step_config(prep), &application, vec![1, 2], vec![3, 4])
        .expect("fixed full F-prime relation");

    let zero = FixedNifsAccumulator::canonical_zero(
        &prep.params,
        prep.structure(),
        prep.combine_b_pows(),
        F_PRIME_PUBLIC_INPUT_LEN,
    )
    .expect("fixed-k zero accumulator");
    let zero_digest = canonical_accumulator_digest(prep);
    let prior_chunk_digest = uniform_chunk_digest(prep, 0);
    let state = FPrimeStateIn {
        vk_fs_digest: context.vk_fs_digest(),
        pi_ccs_header_bundle: context.pi_ccs_header_bundle(),
        chunk_count_in: 1,
        step_count_in: 1,
        z_0: semantic_in,
        z_i_in: prior_chunk_digest,
        pc: 1,
        semantic_state_digest_in: semantic_in,
        acc_digest_in: zero_digest,
        public_trace_in: prior_chunk_digest,
        nebula: None,
    };
    let prior_x_out = native_x_out(&state, prior_chunk_digest, semantic_in, zero_digest, 1, 1);
    let public_input = encode_f_prime_public_input(prior_x_out);
    let mut fresh =
        direct_ccs::build_instance(prep, carrier, &public_input).expect("linked fixed-carrier CCS instance");
    fresh.witness.Z[(FIRST_TAIL_LANE, FIRST_TAIL_BLOCK)] = F::from_u64(TAIL_VALUE);
    fresh.claim.c = prep.log.commit(&fresh.witness.Z);
    let tail_full_decode = decode_superneo_coeffs_from_witness_mat(&fresh.witness.Z, F_PRIME_PUBLIC_INPUT_LEN)
        .expect("linked tail full-carrier decode");
    let fresh_claim = fresh.claim.clone();
    let fresh_claims = [fresh_claim.clone()];
    let chunk_digest = f_prime_chunk_public_digest(state.step_count_in, &fresh_claims);

    let mut prover_transcript = Transcript::with_label(F_PRIME_TRANSCRIPT_LABEL);
    append_f_prime_context(&mut prover_transcript, &state, chunk_digest);
    let (next, proof) = match prove_fixed(
        &mut prover_transcript,
        &prep.params,
        prep.structure(),
        prep.optimized_cache(),
        &prep.log,
        prep.mix_rhos_commits(),
        prep.combine_b_pows(),
        fresh,
        &zero,
    ) {
        Ok(output) => output,
        Err(_) => {
            return LinkedFPrimeOutcome {
                public_input: public_input
                    .iter()
                    .map(PrimeField64::as_canonical_u64)
                    .collect(),
                tail_full_decode: extension_pairs(&tail_full_decode),
                nifs_proved: false,
                nifs_verified: false,
                recursive_f_prime_built: false,
                recursive_f_prime_satisfied: false,
            };
        }
    };

    let verifier_zero = FixedNifsAccumulator::from_verifier_running(
        &prep.params,
        prep.structure(),
        prep.combine_b_pows(),
        zero.running().claims_only(),
    )
    .expect("verifier-side zero accumulator");
    let mut verifier_transcript = Transcript::with_label(F_PRIME_TRANSCRIPT_LABEL);
    append_f_prime_context(&mut verifier_transcript, &state, chunk_digest);
    let nifs_verified = verify_fixed(
        &mut verifier_transcript,
        &prep.params,
        prep.structure(),
        prep.optimized_cache(),
        prep.mix_rhos_commits(),
        prep.combine_b_pows(),
        &fresh_claim,
        &verifier_zero,
        &proof,
    )
    .is_ok();

    let next_digest =
        AccumulatorHandle::from_running_parts(next.claims(), next.running().parent_authority.as_ref()).digest_fields();
    let expected_x_out = native_x_out(&state, chunk_digest, semantic_out, next_digest, 2, 2);
    let source = recursive_source(&state, prior_x_out, expected_x_out);
    let messages = NifsVCircuitMessages {
        fresh: &fresh_claims,
        running: zero.claims(),
        running_parent_authority: zero.running().parent_authority.as_ref(),
        running_pending_projection: zero.running().pending_projection(),
        pi_ccs: &proof.pi_ccs,
        combined: &proof.pi_rlc.combined,
        children: next.claims(),
    };
    let inputs = FPrimeRecursiveInputs {
        state,
        chunk_digest,
        semantic_state_digest_out: semantic_out,
        acc_digest_out: next_digest,
        nifs_msg: messages,
        rows_in_chunk: 1,
        source_image: &source.image,
        chunk_count_in_word: source.chunk_count,
        step_count_in_word: source.step_count,
        pc_word: source.pc,
        prior_x_out_bits: source.prior_x_out,
        public_x_out_bits: source.x_out,
    };
    let execution = relation.build_recursive(&inputs, &application_assignment);
    let (recursive_f_prime_built, recursive_f_prime_satisfied) = match execution {
        Ok(execution) => (true, execution.is_satisfied()),
        Err(_) => (false, false),
    };

    LinkedFPrimeOutcome {
        public_input: public_input
            .iter()
            .map(PrimeField64::as_canonical_u64)
            .collect(),
        tail_full_decode: extension_pairs(&tail_full_decode),
        nifs_proved: true,
        nifs_verified,
        recursive_f_prime_built,
        recursive_f_prime_satisfied,
    }
}

fn capture() -> Snapshot {
    let r1cs = fixed_carrier_r1cs();
    let prep = direct_ccs::preprocess_seeded(&r1cs, PREPROCESS_SEED).expect("fixed carrier preprocessing");
    let zero_assignment = vec![F::ZERO; F_PRIME_PUBLIC_INPUT_LEN];
    let zero = direct_ccs::build_instance(&prep, &r1cs, &zero_assignment).expect("zero fixed-carrier instance");
    let mut tail = zero.clone();
    tail.witness.Z[(FIRST_TAIL_LANE, FIRST_TAIL_BLOCK)] = F::from_u64(TAIL_VALUE);
    tail.claim.c = prep.log.commit(&tail.witness.Z);

    let running = RunningInstance::canonical_zero(&prep.params, prep.structure(), F_PRIME_PUBLIC_INPUT_LEN)
        .expect("canonical fixed-k zero accumulator");
    let fixed_running = FixedNifsAccumulator::canonical_zero(
        &prep.params,
        prep.structure(),
        prep.combine_b_pows(),
        F_PRIME_PUBLIC_INPUT_LEN,
    )
    .expect("canonical fixed Construction-2 accumulator");

    let zero_logical_decode = decode_z_from_witness_mat(prep.params.inner(), &zero.witness.Z, F_PRIME_PUBLIC_INPUT_LEN)
        .expect("zero logical decode");
    let tail_logical_decode = decode_z_from_witness_mat(prep.params.inner(), &tail.witness.Z, F_PRIME_PUBLIC_INPUT_LEN)
        .expect("tail logical decode");
    let zero_full_decode = decode_superneo_coeffs_from_witness_mat(&zero.witness.Z, F_PRIME_PUBLIC_INPUT_LEN)
        .expect("zero full-carrier decode");
    let tail_full_decode = decode_superneo_coeffs_from_witness_mat(&tail.witness.Z, F_PRIME_PUBLIC_INPUT_LEN)
        .expect("tail full-carrier decode");
    let (zero_nifs_proved, zero_nifs_verified) = optimized_nifs_outcome(&prep, &fixed_running, zero.clone());
    let (tail_nifs_proved, tail_nifs_verified) = optimized_nifs_outcome(&prep, &fixed_running, tail.clone());
    let linked = linked_recursive_f_prime_outcome(&prep, &r1cs);

    Snapshot {
        relation_rows: prep.structure().n,
        relation_columns: prep.structure().m,
        relation_arity: prep.structure().t(),
        relation_degree: prep.structure().max_degree(),
        public_input_len: prep.public_input_len.expect("fixed public width"),
        nc_bound: prep.params.b(),
        packed_rows: zero.witness.Z.rows(),
        packed_columns: zero.witness.Z.cols(),
        canonical_running_count: running.claims.len(),
        structure_digest: structure_digest(prep.structure()).map(|value| value.as_canonical_u64()),
        zero_packed_storage: zero
            .witness
            .Z
            .as_slice()
            .iter()
            .map(PrimeField64::as_canonical_u64)
            .collect(),
        tail_packed_storage: tail
            .witness
            .Z
            .as_slice()
            .iter()
            .map(PrimeField64::as_canonical_u64)
            .collect(),
        zero_logical_decode: extension_pairs(&zero_logical_decode),
        tail_logical_decode: extension_pairs(&tail_logical_decode),
        zero_full_decode: extension_pairs(&zero_full_decode),
        tail_full_decode: extension_pairs(&tail_full_decode),
        fresh_public_inputs_equal: zero.claim.x == tail.claim.x,
        commitments_differ: zero.claim.c != tail.claim.c,
        zero_pi_ccs_accepted: optimized_pi_ccs_accepts(&prep, &running, zero),
        tail_pi_ccs_accepted: optimized_pi_ccs_accepts(&prep, &running, tail),
        zero_nifs_proved,
        zero_nifs_verified,
        tail_nifs_proved,
        tail_nifs_verified,
        linked_public_input: linked.public_input,
        linked_tail_full_decode: linked.tail_full_decode,
        linked_tail_nifs_proved: linked.nifs_proved,
        linked_tail_nifs_verified: linked.nifs_verified,
        linked_recursive_f_prime_built: linked.recursive_f_prime_built,
        linked_recursive_f_prime_satisfied: linked.recursive_f_prime_satisfied,
    }
}

fn render_nat_list(values: &[u64]) -> String {
    if values.iter().all(|value| *value == 0) {
        return format!("List.replicate {} 0", values.len());
    }
    let nonzero: Vec<(usize, u64)> = values
        .iter()
        .copied()
        .enumerate()
        .filter(|(_, value)| *value != 0)
        .collect();
    if let [(index, value)] = nonzero.as_slice() {
        return format!("(List.replicate {} 0).set {index} {value}", values.len());
    }
    format!(
        "[{}]",
        values
            .iter()
            .map(u64::to_string)
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn render_extension_list(values: &[(u64, u64)]) -> String {
    if values.iter().all(|value| *value == (0, 0)) {
        return format!("List.replicate {} (0, 0)", values.len());
    }
    let nonzero: Vec<(usize, (u64, u64))> = values
        .iter()
        .copied()
        .enumerate()
        .filter(|(_, value)| *value != (0, 0))
        .collect();
    if let [(index, (c0, c1))] = nonzero.as_slice() {
        return format!("(List.replicate {} (0, 0)).set {index} ({c0}, {c1})", values.len());
    }
    format!(
        "[{}]",
        values
            .iter()
            .map(|(c0, c1)| format!("({c0}, {c1})"))
            .collect::<Vec<_>>()
            .join(", ")
    )
}

fn render_bool(value: bool) -> &'static str {
    if value {
        "true"
    } else {
        "false"
    }
}

